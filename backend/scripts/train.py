#!/usr/bin/env python3
"""Train the original IDS.ipynb models once and export reusable artifacts.

The dataset is NOT bundled. Supply the KDD Cup 1999 10% corrected dataset with
``--data``. Training reproduces the notebook pipeline: deduplication, binary
target, StandardScaler + PCA(0.98), binary CountVectorizer encodings, the custom
Gaussian NB, the custom Gini decision tree, XGBoost and majority voting.

Differences from the notebook (all documented in README.md):
  * a fixed random seed is used so artifacts are reproducible;
  * categorical vocabularies are sorted before being saved (the notebook used
    hash-dependent ``list(set(...))``);
  * evaluation uses one shared stratified 80/20 split instead of the notebook's
    independent splits / trailing slices;
  * the decision tree is exported as JSON rather than a pickle.
"""

from __future__ import annotations

import argparse
import json
import sys
import warnings
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import joblib  # type: ignore
import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.metrics import accuracy_score, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from xgboost import XGBClassifier

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from app.ml.ensemble import majority_vote  # noqa: E402
from app.ml.features import (  # noqa: E402
    CATEGORICAL_FEATURES,
    FEATURES,
    NORMAL_LABEL,
    NUMERIC_FEATURES,
    TARGET_COLUMN,
)
from app.ml.legacy_models import (  # noqa: E402
    GaussianNBFromNotebook,
    build_tree,
    classify,
    tree_to_dict,
)

warnings.filterwarnings("ignore", message="Upper case characters found.*")
warnings.filterwarnings("ignore", category=FutureWarning)

DATASET_URL = "https://kdd.ics.uci.edu/databases/kddcup99/kddcup.data_10_percent.gz"

# Verified from the printed output of the original IDS.ipynb (cell 59).
NOTEBOOK_REFERENCE_METRICS: dict[str, Any] = {
    "source": "Original IDS.ipynb, cell 59 output (historical notebook run)",
    "note": (
        "These numbers are quoted from the original notebook's printed results. "
        "They are NOT a measurement of the artifacts generated by this script."
    ),
    "models": [
        {"name": "Gaussian Naive Bayes", "accuracy_percent": 96.15, "false_positives": 453},
        {"name": "Decision Tree", "accuracy_percent": 99.7, "false_positives": 56},
        {"name": "XGBoost", "accuracy_percent": 99.85, "false_positives": 32},
        {"name": "Max Voting Technique", "accuracy_percent": 99.92, "false_positives": 14},
    ],
}


def evaluate(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, Any]:
    """Accuracy plus the notebook's definition of a false positive."""
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "accuracy_percent": round(float(accuracy_score(y_true, y_pred) * 100), 2),
        "false_positives": int(fp),
        "false_negatives": int(fn),
        "true_positives": int(tp),
        "true_negatives": int(tn),
        "samples": int(len(y_true)),
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="Path to kddcup.data_10_percent_corrected")
    parser.add_argument(
        "--output",
        default=str(BACKEND_DIR / "models"),
        help="Directory for exported artifacts (default: backend/models)",
    )
    parser.add_argument("--seed", type=int, default=42, help="Random seed (default: 42)")
    parser.add_argument("--test-size", type=float, default=0.2, help="Held-out fraction (default: 0.2)")
    parser.add_argument("--dt-training-rows", type=int, default=10000, help="Rows for custom tree")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    data_path = Path(args.data)
    output_dir = Path(args.output)
    if not data_path.is_file():
        raise SystemExit(f"Dataset not found: {data_path}")

    print(f"[1/7] Loading {data_path}")
    frame = pd.read_csv(data_path, names=FEATURES + [TARGET_COLUMN], header=None)
    if frame.empty:
        raise SystemExit("Dataset is empty.")
    rows_read = int(len(frame))
    duplicates = int(frame.duplicated().sum())
    frame.drop_duplicates(keep="first", inplace=True)
    frame.reset_index(drop=True, inplace=True)
    labels = sorted(str(value) for value in frame[TARGET_COLUMN].unique())
    target = np.asarray(
        [1 if str(value) == NORMAL_LABEL else 0 for value in frame[TARGET_COLUMN]],
        dtype=int,
    )
    print(f"      rows={rows_read}, duplicates removed={duplicates}, clean rows={len(frame)}")

    print("[2/7] Fitting StandardScaler + PCA(n_components=0.98) on numeric features")
    numeric_frame = frame[NUMERIC_FEATURES]
    scaler = StandardScaler().fit(numeric_frame)
    scaled = scaler.transform(numeric_frame)
    pca = PCA(n_components=0.98, random_state=args.seed).fit(scaled)
    pca_values = pca.transform(scaled)
    pca_frame = pd.DataFrame(pca_values)
    print(f"      PCA components={pca_values.shape[1]}")

    print("[3/7] Encoding categorical features with binary CountVectorizer")
    categorical_values: dict[str, list[str]] = {}
    encoded_parts = []
    for column in CATEGORICAL_FEATURES:
        values = frame[column].astype(str).tolist()
        # The notebook used list(set(values)), whose order depends on the hash
        # seed. Sorting makes training reproducible; the order is saved and
        # reused unchanged at inference time.
        vocab = sorted(set(values))
        categorical_values[column] = vocab
        vectorizer = CountVectorizer(vocabulary=vocab, binary=True)
        encoded_parts.append(vectorizer.fit_transform(values).toarray())
        print(f"      {column}: {len(vocab)} values")

    xgb_matrix = np.hstack((pca_values, *encoded_parts))
    xgb_frame = pd.DataFrame(xgb_matrix)

    print("[4/7] Creating shared stratified train/test split")
    indices = np.arange(len(frame))
    train_index, test_index = train_test_split(
        indices,
        test_size=args.test_size,
        random_state=args.seed,
        stratify=target,
    )
    y_train, y_test = target[train_index], target[test_index]

    print("[5/7] Training Gaussian NB, custom Decision Tree and XGBoost")
    gnb = GaussianNBFromNotebook().fit(
        pca_frame.iloc[train_index].reset_index(drop=True),
        pd.Series(y_train),
    )

    frame_dt = frame[FEATURES].copy()
    frame_dt["target"] = target
    tree_sample = (
        frame_dt.iloc[train_index]
        .sample(n=min(args.dt_training_rows, len(train_index)), random_state=args.seed)
        .reset_index(drop=True)
    )
    tree = build_tree(tree_sample.values.tolist())

    xgb_model = XGBClassifier(
        objective="binary:logistic",
        eval_metric="logloss",
        n_estimators=100,
        max_depth=6,
        learning_rate=0.3,
        subsample=1.0,
        colsample_bytree=1.0,
        random_state=args.seed,
        n_jobs=-1,
    )
    xgb_model.fit(xgb_frame.iloc[train_index], y_train)

    print("[6/7] Evaluating models and majority-vote ensemble")
    gnb_pred = np.asarray([gnb.predict(pca_frame.iloc[i].to_numpy()) for i in test_index], dtype=int)
    dt_test_rows = frame_dt.iloc[test_index].values.tolist()
    dt_pred = np.asarray(
        [
            sorted(classify(row, tree).items(), key=lambda item: item[1], reverse=True)[0][0]
            for row in dt_test_rows
        ],
        dtype=int,
    )
    xgb_pred = np.asarray(xgb_model.predict(xgb_frame.iloc[test_index]), dtype=int)
    ensemble_pred = np.asarray(
        [majority_vote(votes) for votes in zip(gnb_pred, dt_pred, xgb_pred)],
        dtype=int,
    )

    artifact_metrics = {
        "Gaussian Naive Bayes": evaluate(y_test, gnb_pred),
        "Decision Tree": evaluate(y_test, dt_pred),
        "XGBoost": evaluate(y_test, xgb_pred),
        "Max Voting Technique": evaluate(y_test, ensemble_pred),
    }
    for name, values in artifact_metrics.items():
        print(f"      {name}: accuracy={values['accuracy_percent']}% FP={values['false_positives']}")

    print(f"[7/7] Writing artifacts to {output_dir}")
    output_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(scaler, output_dir / "scaler.joblib")
    joblib.dump(pca, output_dir / "pca.joblib")
    gnb.save(output_dir / "gnb.npz")
    (output_dir / "dt_tree.json").write_text(
        json.dumps(tree_to_dict(tree)), encoding="utf-8"
    )
    xgb_model.save_model(output_dir / "xgb_model.json")

    metadata: dict[str, Any] = {
        "version": "kdd99-nb-dt-xgb-v1",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "source_notebook": "IDS.ipynb from JayantUppal/Intrusion-Detection-System",
        "model_name": "Gaussian Naive Bayes + Decision Tree + XGBoost (majority vote)",
        "dataset": {
            "name": "KDD Cup 1999 10% corrected",
            "source_url": DATASET_URL,
            "rows_read": rows_read,
            "rows_after_deduplication": int(len(frame)),
            "duplicate_rows_removed": duplicates,
            "normal_rows": int(np.sum(target == 1)),
            "attack_rows": int(np.sum(target == 0)),
            "intrusion_type_labels": labels,
        },
        "features": FEATURES,
        "numeric_features": NUMERIC_FEATURES,
        "categorical_features": CATEGORICAL_FEATURES,
        "categorical_values": categorical_values,
        "label_mapping": {"0": "ATTACK", "1": "NORMAL"},
        "original_target_rule": "intrusion_type == 'normal.' -> 1; all other 22 labels -> 0",
        "preprocessing": {
            "numeric_order": "df.select_dtypes(include=['float64','int64']) from IDS.ipynb",
            "scaler": "StandardScaler",
            "pca_variance_threshold": 0.98,
            "pca_components": int(pca_values.shape[1]),
            "categorical_encoding": "CountVectorizer(vocabulary=saved values, binary=True)",
            "decision_tree_input": "all 41 predictors in original notebook column order",
            "note": (
                "Scaler, PCA and categorical vocabularies are fitted on the full "
                "cleaned dataset, exactly as in the original notebook. Artifacts "
                "are loaded once at API startup; no retraining happens per request."
            ),
        },
        "ensemble": {
            "method": "majority / max voting",
            "models": ["gaussian_naive_bayes", "decision_tree", "xgboost"],
            "decision_rule": "np.bincount([gnb, dt, xgb]).argmax()",
            "confidence": "winning votes / 3 (model agreement, not a calibrated probability)",
        },
        "training": {
            "seed": args.seed,
            "test_size": args.test_size,
            "decision_tree_training_rows": int(min(args.dt_training_rows, len(train_index))),
            "split_strategy": "stratified 80/20, shared by all three models",
            "note": (
                "The original notebook used unseeded splits and a trailing 20% "
                "slice for the ensemble evaluation; this training script uses a "
                "fixed shared split for comparable artifact metrics."
            ),
        },
        "artifacts": {
            "scaler": "scaler.joblib",
            "pca": "pca.joblib",
            "gnb": "gnb.npz",
            "decision_tree": "dt_tree.json",
            "xgb": "xgb_model.json",
        },
        "xgboost_features": int(xgb_matrix.shape[1]),
        "license_note": (
            "The upstream repository contains no LICENSE file; redistribution "
            "rights are not granted. Check with the original author before sharing."
        ),
    }
    (output_dir / "metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    (output_dir / "metrics.json").write_text(
        json.dumps(
            {
                "artifact_metrics": artifact_metrics,
                "notebook_reference_metrics": NOTEBOOK_REFERENCE_METRICS,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print("Done. Start the API with: uvicorn app.main:app --host 0.0.0.0 --port 8000")


if __name__ == "__main__":
    main()
